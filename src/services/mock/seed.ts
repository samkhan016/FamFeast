function buildPlan(theme: WeeklyThemeId): WeeklyPlan {
  const days = weekDates();
  const start = toISODate(days[0]);
  const end = toISODate(days[6]);
  const dinnerMap: Array<{recipeId: string; chefId: string}> = [
    {recipeId: 'lemon-salmon', chefId: 'mom'},
    {recipeId: 'street-tacos', chefId: 'leo'},
    {recipeId: 'thai-curry', chefId: 'mom'},
    {recipeId: 'honey-chicken', chefId: 'mom'},
    {recipeId: 'diy-pizza', chefId: 'dad'},
    {recipeId: 'smash-burgers', chefId: 'dad'},
    {recipeId: 'pot-roast', chefId: 'mom'},
  ];
  const lunchMap = ['tomato-penne', 'halloumi-wraps', 'sun-orzo', 'tomato-penne', 'sheet-fajitas', 'loaded-nachos', 'lentil-curry'];
  const breakfastMap = ['berry-oats', 'berry-oats', 'berry-oats', 'berry-oats', 'berry-oats', 'buttermilk-pancakes', 'buttermilk-pancakes'];
  const chefForBreakfast = ['maya', 'maya', 'maya', 'maya', 'maya', 'dad', 'dad'];

  const slots = days.flatMap((day, index) => {
    const date = toISODate(day);
    return [
      {
        id: `slot_${date}_breakfast`,
        date,
        mealType: 'breakfast' as const,
        recipeId: breakfastMap[index],
        chefId: chefForBreakfast[index],
        status: index < 3 ? ('served' as const) : ('planned' as const),
      },
      {
        id: `slot_${date}_lunch`,
        date,
        mealType: 'lunch' as const,
        recipeId: lunchMap[index],
        chefId: index === 5 || index === 6 ? 'dad' : 'dad',
        status: index < 3 ? ('served' as const) : index === 3 ? ('prepped' as const) : ('planned' as const),
      },
      {
        id: `slot_${date}_dinner`,
        date,
        mealType: 'dinner' as const,
        recipeId: dinnerMap[index].recipeId,
        chefId: dinnerMap[index].chefId,
        helperId: dinnerMap[index].recipeId === 'honey-chicken' ? 'maya' : undefined,
        status: 'planned' as const,
      },
    ];
  });

  const todayDinner = slots.find(s => s.mealType === 'dinner' && s.date === toISODate(new Date()));

  return {
    weekId: weekIdFor(),
    startDate: start,
    endDate: end,
    theme,
    moodId: 'sweet',
    energyLabel: 'Mood: Post-School Tired 🥱 → Sweet & light meals prioritized!',
    slots,
    prepTasks: todayDinner
      ? [
          {id: 'prep1', slotId: todayDinner.id, label: 'Thaw chicken tenders from freezer', minutes: 2, done: true},
          {id: 'prep2', slotId: todayDinner.id, label: 'Finely dice scallions, garlic & fresh parsley', minutes: 5, done: false},
          {id: 'prep3', slotId: todayDinner.id, label: 'Rinse and steam 2 cups jasmine rice', minutes: 15, done: false},
        ]
      : [],
  };
}

